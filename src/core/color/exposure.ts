import type { Rgb } from '../types'

/**
 * 노출 정규화 — 사진의 밝기를 맞춘다.
 *
 * 조명 색 보정(whiteBalance)은 **색만** 잡는다. 밝기는 그대로 노출에 끌려다녔다:
 * 2026-08-22 실측에서 같은 사람도 노출이 ±35% 흔들리면 피부 L*이 45나 벌어졌고,
 * 이는 사람 사이의 차이(28)보다 컸다 — 판정이 사람이 아니라 조명을 재고 있었다.
 * 정규화 후에는 12 대 22로 역전돼 **사람 쪽이 우세**해진다.
 *
 * 기준자는 색 보정과 같은 눈 흰자다. 흰자는 사진 안에서 밝기가 가장 안정적인
 * 무채색 영역이라, 그 밝기를 고정하면 노출이 따라 고정된다.
 *
 * **한계 둘 — 둘 다 감수한 것이다.**
 *   1. 흰자 밝기는 사람마다 조금씩 다르다(어두운 피부일수록 흰자도 어둡게 찍히는
 *      경향). 그래서 정규화가 **사람 사이 차이도 일부 누른다** — 실측에서 28.2가
 *      21.7로 23% 줄었다. 조명 편차가 그보다 훨씬 크게 줄어 교환이 성립한다.
 *   2. 아주 밝게 찍혀 흰자가 흰색으로 날아간(클리핑) 사진은 기준을 못 잡는다.
 *      그 경우 호출부가 정규화를 건너뛴다.
 */

/**
 * 흰자를 이 밝기로 맞춘다. 단위는 **sRGB 가중 평균 밝기(0~255)**다 —
 * L*(0~100)가 아니다. 두 스케일을 섞으면 배율이 거꾸로 나온다(실제로 한 번 겪었다).
 *
 * 232는 L* 92에 해당하는 값이고, 실제 흰자의 밝기 범위(207~234) 안에 든다.
 * 이 값으로 정규화하면 대표 피부 4종의 L*이 55.6~77.4에 놓여 지금의 명도
 * 경계(68)를 사이에 두고 갈린다.
 *
 * **표본이 적어 잠정값이다.** 동료 배포로 흰자 밝기 실측이 쌓이면 다시 잡는다.
 */
export const TARGET_REFERENCE_LUMA = 232

/** 배율 상·하한 — 극단 보정으로 사진이 타거나 뭉개지는 것을 막는다 */
const MIN_GAIN = 0.4
const MAX_GAIN = 3

function luma(color: Rgb): number {
  return color.r * 0.299 + color.g * 0.587 + color.b * 0.114
}

/**
 * 기준색(눈 흰자)을 목표 밝기로 옮기는 배율을 낸다.
 *
 * sRGB 값에 그대로 곱하는 단순 배율이다. 감마를 풀고 곱한 뒤 되감는 편이
 * 물리적으로는 정확하지만, 여기서 재는 것은 **표본 사이의 상대 위치**라
 * 두 방식의 차이가 판정을 바꾸지 않는다.
 *
 * 근거: sRGB는 근사적으로 거듭제곱 인코딩이고 거듭제곱은 곱셈과 교환된다
 * (`(a·x)^p = a^p · x^p`). 그래서 "빛이 e배 됐다"는 사건은 인코딩 공간에서도
 * **모든 밝기에 같은 상수 배율**로 나타난다 — 배율 값 자체는 다르지만
 * "기준으로 잰 배율이 피부에도 그대로 통한다"는 성질은 유지된다.
 * 단 이 등가성은 **클리핑이 없을 때만** 성립한다.
 */
export function estimateExposureGain(reference: Rgb): number {
  const current = luma(reference)

  if (current <= 0) {
    return 1
  }

  const raw = TARGET_REFERENCE_LUMA / current

  return Math.min(MAX_GAIN, Math.max(MIN_GAIN, raw))
}

/**
 * 채널 배율에 노출 배율을 곱한다 — 색 보정과 밝기 보정을 한 번에 적용하기 위해서다.
 */
export function combineGain(channelGain: Rgb, exposure: number): Rgb {
  return {
    r: channelGain.r * exposure,
    g: channelGain.g * exposure,
    b: channelGain.b * exposure,
  }
}
